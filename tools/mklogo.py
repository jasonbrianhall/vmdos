#!/usr/bin/env python3
"""Build src/logo.h: icon.png, shrunk and cut to 16 colours, run-length
coded, for the boot console's corner (bootcon.c). Only needed to regenerate
the checked-in header.  Usage: tools/mklogo.py [icon.png] [width] > src/logo.h

Coding: one byte per run, colour index in the high nibble, run length - 1
in the low (1..16 pixels); runs go on across rows."""
import sys
from PIL import Image

src = sys.argv[1] if len(sys.argv) > 1 else "icon.png"
W = int(sys.argv[2]) if len(sys.argv) > 2 else 96

im = Image.open(src).convert("RGB")
H = round(im.height * W / im.width)
im = im.resize((W, H), Image.LANCZOS)
q = im.quantize(colors=16, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
pal = q.getpalette()[:16 * 3]
px = list(q.tobytes())

runs = []
i = 0
while i < len(px):
    c, n = px[i], 1
    while n < 16 and i + n < len(px) and px[i + n] == c:
        n += 1
    runs.append(c << 4 | (n - 1))
    i += n

out = sys.stdout
out.write("/* Generated by tools/mklogo.py from icon.png: do not edit. */\n")
out.write(f"#define LOGO_W {W}\n#define LOGO_H {H}\n")
out.write("static const u8 logo_pal[16][3] = {\n")
for k in range(16):
    r, g, b = pal[k * 3:k * 3 + 3] if k * 3 + 2 < len(pal) else (0, 0, 0)
    out.write(f"    {{{r}, {g}, {b}}},\n")
out.write("};\n")
out.write(f"static const u8 logo_rle[{len(runs)}] = {{\n")
for j in range(0, len(runs), 16):
    out.write("    " + ", ".join(f"0x{b:02x}" for b in runs[j:j + 16]) + ",\n")
out.write("};\n")
print(f"{W}x{H}: {len(runs)} bytes of runs", file=sys.stderr)
